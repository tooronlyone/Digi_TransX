CREATE TABLE IF NOT EXISTS public.fuel_platform_treasury (
    singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
    wallet_id bigint NOT NULL UNIQUE REFERENCES public.wallets(id) ON DELETE RESTRICT,
    verified_liquidity numeric(20,2) NOT NULL CHECK(verified_liquidity>=0),
    funding_evidence text NOT NULL CHECK(length(trim(funding_evidence))>=10),
    verified_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    verified_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.guard_fuel_treasury_identity()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'Treasury wallet binding is immutable; explicit financial reconciliation is required' USING ERRCODE='23514';
END $$;
REVOKE ALL ON FUNCTION public.guard_fuel_treasury_identity() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS treasury_identity_immutable ON public.fuel_platform_treasury;
CREATE TRIGGER treasury_identity_immutable BEFORE UPDATE OF wallet_id OR DELETE ON public.fuel_platform_treasury
    FOR EACH ROW EXECUTE FUNCTION public.guard_fuel_treasury_identity();

CREATE TABLE IF NOT EXISTS public.fuel_credit_accounts (
    transporter_user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE RESTRICT,
    authorized_limit numeric(20,2) NOT NULL DEFAULT 0 CHECK(authorized_limit IN(0,10000,20000)),
    reserved_credit numeric(20,2) NOT NULL DEFAULT 0 CHECK(reserved_credit>=0),
    outstanding_credit numeric(20,2) NOT NULL DEFAULT 0 CHECK(outstanding_credit>=0),
    utilized_credit numeric(20,2) NOT NULL DEFAULT 0 CHECK(utilized_credit>=0),
    recovered_credit numeric(20,2) NOT NULL DEFAULT 0 CHECK(recovered_credit>=0),
    released_credit numeric(20,2) NOT NULL DEFAULT 0 CHECK(released_credit>=0),
    cancellation_debt boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK(outstanding_credit=utilized_credit-recovered_credit)
);

CREATE TABLE IF NOT EXISTS public.fuel_vouchers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transporter_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    trip_id bigint REFERENCES public.shipment_trips(id) ON DELETE RESTRICT,
    -- Note: V1-era Agreemental bridge also had agreement_trip_id; V2 redesign should bridge explicitly if agreements return
    truck_id bigint NOT NULL REFERENCES public.vehicles(id) ON DELETE RESTRICT,
    truck_plate text NOT NULL,
    fuel_type text NOT NULL CHECK(fuel_type IN('diesel','petrol','hi_octane','cng','adblue')),
    request_mode text NOT NULL CHECK(request_mode IN('tank_full','liters','amount')),
    max_amount numeric(20,2) NOT NULL CHECK(max_amount>0),
    max_liters numeric(16,2) CHECK(max_liters>0),
    wallet_authorized numeric(20,2) NOT NULL CHECK(wallet_authorized>=0),
    credit_authorized numeric(20,2) NOT NULL CHECK(credit_authorized>=0),
    restricted_station_id bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    redeemed_station_id bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    pump_id bigint REFERENCES public.fuel_station_pumps(id) ON DELETE RESTRICT,
    otp_digest bytea NOT NULL UNIQUE,
    redemption_digest bytea UNIQUE,
    idempotency_key text NOT NULL,
    request_hash text NOT NULL,
    status text NOT NULL DEFAULT 'authorized' CHECK(status IN('authorized','verified','dispensed','cancelled','expired')),
    expires_at timestamptz NOT NULL,
    actual_amount numeric(20,2),
    actual_liters numeric(16,2),
    wallet_utilized numeric(20,2),
    credit_utilized numeric(20,2),
    dispense_id bigint UNIQUE REFERENCES public.fuel_station_dispenses(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    verified_at timestamptz,
    finalized_at timestamptz,
    UNIQUE(transporter_user_id,idempotency_key),
    CHECK(trip_id IS NOT NULL),
    CHECK(max_amount=wallet_authorized+credit_authorized),
    CHECK(request_mode<>'liters' OR max_liters IS NOT NULL),
    CHECK(actual_amount IS NULL OR (actual_amount>0 AND actual_amount<=max_amount)),
    CHECK(actual_liters IS NULL OR (actual_liters>0 AND (max_liters IS NULL OR actual_liters<=max_liters))),
    CHECK(status<>'dispensed' OR (actual_amount=wallet_utilized+credit_utilized AND dispense_id IS NOT NULL AND finalized_at IS NOT NULL)),
    CHECK(status NOT IN('verified','dispensed') OR (redeemed_station_id IS NOT NULL AND redemption_digest IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS fuel_vouchers_owner_recent ON public.fuel_vouchers(transporter_user_id,id DESC);
CREATE INDEX IF NOT EXISTS fuel_vouchers_due ON public.fuel_vouchers(expires_at) WHERE status IN('authorized','verified');

