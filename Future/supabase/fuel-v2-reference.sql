-- 7. Finite numeric money checks
DO $$ DECLARE relation_name text; column_name text; predicate text; BEGIN
    FOREACH relation_name IN ARRAY ARRAY['fuel_platform_treasury','fuel_credit_accounts','fuel_vouchers','fuel_credit_events'] LOOP
        predicate:='true';
        FOR column_name IN SELECT c.column_name FROM information_schema.columns c
            WHERE c.table_schema='public' AND c.table_name=relation_name AND c.data_type='numeric' LOOP
            predicate:=predicate||format(' AND (%I IS NULL OR %I <> ''NaN''::numeric)',column_name,column_name);
        END LOOP;
        IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid=format('public.%I',relation_name)::regclass AND conname='finite_money') THEN
            EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT finite_money CHECK(%s)',relation_name,predicate);
        END IF;
    END LOOP;
END $$;
