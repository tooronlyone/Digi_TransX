begin
    foreach client_role in array array['anon', 'authenticated'] loop
        if exists (
            select 1
            from pg_catalog.pg_roles
            where rolname = client_role
        ) then
            execute format(
                'grant execute on function '
                'public.is_transporter_assigned_to_shipment(bigint) to %I',
                client_role
            );
        end if;
    end loop;
end
$$;

