CREATE OR REPLACE FUNCTION public.guard_operational_incident_history()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.status<>'investigating' OR NEW.decision_by IS NOT NULL OR NEW.decision_at IS NOT NULL THEN
            RAISE EXCEPTION 'New incidents require investigation before a decision' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' OR OLD.status<>'investigating' THEN
        RAISE EXCEPTION 'Incident evidence and finalized decisions are immutable' USING ERRCODE='23514';
    END IF;
    IF (NEW.assignment_id,NEW.reporter_user_id,NEW.incident_type,NEW.description,NEW.evidence,NEW.created_at)
       IS DISTINCT FROM (OLD.assignment_id,OLD.reporter_user_id,OLD.incident_type,OLD.description,OLD.evidence,OLD.created_at) THEN
        RAISE EXCEPTION 'Submitted incident evidence and provenance are immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.status IN('confirmed','dismissed') AND NOT EXISTS(SELECT 1 FROM public.users WHERE id=NEW.decision_by AND role='admin') THEN
        RAISE EXCEPTION 'An authorized investigation decision is required' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
