    on public.shipment_bids (order_id, id);
create unique index uq_bids_id_order_transp_truck
    on public.shipment_bids (id, order_id, transporter_user_id, truck_id);
create unique index uq_trips_id_order
    on public.shipment_trips (id, order_id);
create unique index uq_trips_id_transporter
    on public.shipment_trips (id, transporter_user_id);
create unique index uq_shipments_id_client
    on public.shipments (id, client_user_id);
create unique index uq_payments_id_trip
    on public.payments (id, trip_id);
create unique index uq_chat_threads_id_shipment_trip
    on public.chat_threads (id, shipment_id, one_time_trip_id);

