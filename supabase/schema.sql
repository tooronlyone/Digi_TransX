-- Composite foreign keys so related one-time IDs can never disagree (a bid,
-- trip, payment, dispute or chat thread cannot borrow another order's, truck's
-- or party's row). Each references a composite UNIQUE INDEX below; a single-
-- column primary key does not by itself satisfy a multi-column FK target, so
-- these indexes exist purely as FK anchors. Referencing columns that the
-- current workflow may leave NULL (accepted_bid_id, payments.shipment_id,
-- payment_id, chat_thread_id, one_time_trip_id) rely on MATCH SIMPLE: when any
-- referencing column is NULL the whole FK is skipped, so legacy NULL paths stay
-- valid. Every check protects INSERT and UPDATE. Mirrors migration
-- 20260723120000 sections 12-13.

