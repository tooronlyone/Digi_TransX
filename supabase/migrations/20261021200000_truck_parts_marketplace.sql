-- Truck Parts & Services In-App Marketplace for Digi_TransX

-- 1. Parts Catalog / Products
CREATE TABLE IF NOT EXISTS public.marketplace_parts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    part_number TEXT,
    brand TEXT,
    category TEXT NOT NULL, -- tyres, engine, brakes, suspension, electrical, lubricants, body
    condition TEXT NOT NULL DEFAULT 'new_oem' CHECK (condition IN ('new_oem', 'new_aftermarket', 'kabli', 'refurbished')),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    discounted_price NUMERIC(12,2),
    stock_quantity INT NOT NULL DEFAULT 1 CHECK (stock_quantity >= 0),
    warranty_days INT DEFAULT 0,
    images JSONB DEFAULT '[]'::jsonb,
    description TEXT,
    compatible_models JSONB NOT NULL DEFAULT '[]'::jsonb,
    city TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_marketplace_parts_shop ON public.marketplace_parts(shop_user_id);
CREATE INDEX IF NOT EXISTS idx_marketplace_parts_category ON public.marketplace_parts(category);
CREATE INDEX IF NOT EXISTS idx_marketplace_parts_active ON public.marketplace_parts(is_active);

-- 2. Marketplace Orders (Escrow & Delivery)
CREATE TABLE IF NOT EXISTS public.marketplace_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    buyer_user_id BIGINT NOT NULL REFERENCES public.users(id),
    shop_user_id BIGINT NOT NULL REFERENCES public.users(id),
    vehicle_id BIGINT REFERENCES public.vehicles(id) ON DELETE SET NULL,
    delivery_type TEXT NOT NULL DEFAULT 'delivery' CHECK (delivery_type IN ('delivery', 'pickup')),
    delivery_address TEXT,
    delivery_lat DOUBLE PRECISION,
    delivery_lng DOUBLE PRECISION,
    contact_phone TEXT,
    total_parts_amount NUMERIC(12,2) NOT NULL CHECK (total_parts_amount >= 0),
    delivery_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    platform_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (platform_fee >= 0),
    net_total NUMERIC(12,2) NOT NULL CHECK (net_total >= 0),
    payment_method TEXT NOT NULL DEFAULT 'wallet_escrow' CHECK (payment_method IN ('wallet_escrow', 'cod', 'online')),
    payment_status TEXT NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'escrow_locked', 'released', 'refunded')),
    fulfillment_status TEXT NOT NULL DEFAULT 'placed' 
        CHECK (fulfillment_status IN ('placed', 'confirmed', 'dispatched', 'ready_for_pickup', 'delivered', 'cancelled', 'returned')),
    delivery_otp TEXT,
    buyer_notes TEXT,
    cancelled_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_marketplace_orders_buyer ON public.marketplace_orders(buyer_user_id);
CREATE INDEX IF NOT EXISTS idx_marketplace_orders_shop ON public.marketplace_orders(shop_user_id);
CREATE INDEX IF NOT EXISTS idx_marketplace_orders_status ON public.marketplace_orders(fulfillment_status);

-- 3. Marketplace Order Items
CREATE TABLE IF NOT EXISTS public.marketplace_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.marketplace_orders(id) ON DELETE CASCADE,
    part_id BIGINT REFERENCES public.marketplace_parts(id) ON DELETE SET NULL,
    part_title TEXT NOT NULL,
    part_number TEXT,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    quantity INT NOT NULL CHECK (quantity > 0),
    warranty_days INT DEFAULT 0,
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_marketplace_order_items_order ON public.marketplace_order_items(order_id);

-- 4. Part RFQs (Emergency / Custom Part Broadcast)
CREATE TABLE IF NOT EXISTS public.part_rfqs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transporter_user_id BIGINT NOT NULL REFERENCES public.users(id),
    vehicle_id BIGINT REFERENCES public.vehicles(id) ON DELETE SET NULL,
    part_name TEXT NOT NULL,
    category TEXT,
    description TEXT,
    sample_photos JSONB DEFAULT '[]'::jsonb,
    urgency TEXT DEFAULT 'normal' CHECK (urgency IN ('low', 'normal', 'breakdown_emergency')),
    city TEXT NOT NULL,
    location_lat DOUBLE PRECISION,
    location_lng DOUBLE PRECISION,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'fulfilled', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_part_rfqs_transporter ON public.part_rfqs(transporter_user_id);
CREATE INDEX IF NOT EXISTS idx_part_rfqs_status ON public.part_rfqs(status);

-- 5. RFQ Quotes (Bids by Shops)
CREATE TABLE IF NOT EXISTS public.part_rfq_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id BIGINT NOT NULL REFERENCES public.part_rfqs(id) ON DELETE CASCADE,
    shop_user_id BIGINT NOT NULL REFERENCES public.users(id),
    offered_price NUMERIC(12,2) NOT NULL CHECK (offered_price >= 0),
    condition TEXT NOT NULL DEFAULT 'new_oem',
    brand TEXT,
    warranty_days INT DEFAULT 0,
    delivery_time_hours INT NOT NULL DEFAULT 2,
    note TEXT,
    status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'accepted', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_part_rfq_bids_rfq ON public.part_rfq_bids(rfq_id);
CREATE INDEX IF NOT EXISTS idx_part_rfq_bids_shop ON public.part_rfq_bids(shop_user_id);

-- 6. Enable Row Level Security (RLS)
ALTER TABLE public.marketplace_parts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.marketplace_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.marketplace_order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.part_rfqs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.part_rfq_bids ENABLE ROW LEVEL SECURITY;

-- RLS Policies
-- Parts: Everyone authenticated can view active parts
CREATE POLICY parts_read_all ON public.marketplace_parts
    FOR SELECT USING (is_active = true OR shop_user_id = public.current_app_user_id());

-- Parts: Shops can manage their own parts
CREATE POLICY parts_shop_manage ON public.marketplace_parts
    FOR ALL USING (shop_user_id = public.current_app_user_id())
    WITH CHECK (shop_user_id = public.current_app_user_id());

-- Orders: Buyer and Seller can read their orders
CREATE POLICY orders_read_parties ON public.marketplace_orders
    FOR SELECT USING (buyer_user_id = public.current_app_user_id() OR shop_user_id = public.current_app_user_id());

-- RFQ: All can read open RFQs, transporter can read their own
CREATE POLICY rfq_read ON public.part_rfqs
    FOR SELECT USING (status = 'open' OR transporter_user_id = public.current_app_user_id());

-- RFQ Bids: Shop who placed it and Transporter who posted RFQ can read
CREATE POLICY rfq_bids_read ON public.part_rfq_bids
    FOR SELECT USING (
        shop_user_id = public.current_app_user_id()
        OR rfq_id IN (SELECT id FROM public.part_rfqs WHERE transporter_user_id = public.current_app_user_id())
    );
