-- Rules 1-4: append-only, balanced journal for new financial operations.
-- No historical balances, wallet transactions, or settlement snapshots change.
CREATE TABLE IF NOT EXISTS public.financial_journal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key text NOT NULL UNIQUE CHECK(length(idempotency_key) BETWEEN 1 AND 200),
    kind text NOT NULL,
    reference text NOT NULL,
    payload_hash text NOT NULL,
    created_txid bigint NOT NULL DEFAULT txid_current(),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.financial_journal_lines (
    journal_id bigint NOT NULL REFERENCES public.financial_journal(id) ON DELETE RESTRICT,
    account text NOT NULL CHECK(length(account) BETWEEN 1 AND 200),
    amount numeric(20,2) NOT NULL CHECK(amount <> 0 AND amount <> 'NaN'::numeric),
    PRIMARY KEY(journal_id,account)
);
CREATE OR REPLACE FUNCTION public.reject_financial_record_mutation()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION 'Financial records are immutable; post an explicit reversal' USING ERRCODE='23514'; END $$;
REVOKE ALL ON FUNCTION public.reject_financial_record_mutation() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS journal_immutable ON public.financial_journal;
CREATE TRIGGER journal_immutable BEFORE UPDATE OR DELETE ON public.financial_journal
    FOR EACH ROW EXECUTE FUNCTION public.reject_financial_record_mutation();
DROP TRIGGER IF EXISTS journal_lines_immutable ON public.financial_journal_lines;
CREATE TRIGGER journal_lines_immutable BEFORE UPDATE OR DELETE ON public.financial_journal_lines
    FOR EACH ROW EXECUTE FUNCTION public.reject_financial_record_mutation();
CREATE OR REPLACE FUNCTION public.guard_journal_line_insert()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM public.financial_journal WHERE id=NEW.journal_id AND created_txid=txid_current()) THEN
        RAISE EXCEPTION 'Cannot append to a committed financial journal' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.guard_journal_line_insert() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS journal_lines_insert_guard ON public.financial_journal_lines;
CREATE TRIGGER journal_lines_insert_guard BEFORE INSERT ON public.financial_journal_lines
    FOR EACH ROW EXECUTE FUNCTION public.guard_journal_line_insert();
DROP TRIGGER IF EXISTS journal_no_truncate ON public.financial_journal;
CREATE TRIGGER journal_no_truncate BEFORE TRUNCATE ON public.financial_journal
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_financial_record_mutation();
DROP TRIGGER IF EXISTS journal_lines_no_truncate ON public.financial_journal_lines;
CREATE TRIGGER journal_lines_no_truncate BEFORE TRUNCATE ON public.financial_journal_lines
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_financial_record_mutation();
CREATE OR REPLACE FUNCTION public.validate_financial_journal_balance()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
DECLARE target bigint; total numeric; legs integer;
BEGIN
    IF TG_TABLE_NAME='financial_journal' THEN target:=NEW.id; ELSE target:=NEW.journal_id; END IF;
    SELECT coalesce(sum(amount),0),count(*) INTO total,legs FROM public.financial_journal_lines WHERE journal_id=target;
    IF total<>0 OR legs<2 THEN RAISE EXCEPTION 'Unbalanced financial journal %',target USING ERRCODE='23514'; END IF;
    RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.validate_financial_journal_balance() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS journal_balanced ON public.financial_journal;
CREATE CONSTRAINT TRIGGER journal_balanced AFTER INSERT ON public.financial_journal
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_financial_journal_balance();
DROP TRIGGER IF EXISTS journal_lines_balanced ON public.financial_journal_lines;
CREATE CONSTRAINT TRIGGER journal_lines_balanced AFTER INSERT ON public.financial_journal_lines
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_financial_journal_balance();
ALTER TABLE public.financial_journal ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.financial_journal_lines ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.financial_journal,public.financial_journal_lines FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.financial_journal_id_seq FROM anon,authenticated;
GRANT SELECT,INSERT ON public.financial_journal,public.financial_journal_lines TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.financial_journal_id_seq TO service_role;
DROP POLICY IF EXISTS journal_backend ON public.financial_journal;
CREATE POLICY journal_backend ON public.financial_journal FOR ALL TO service_role USING(true) WITH CHECK(true);
DROP POLICY IF EXISTS journal_lines_backend ON public.financial_journal_lines;
CREATE POLICY journal_lines_backend ON public.financial_journal_lines FOR ALL TO service_role USING(true) WITH CHECK(true);
