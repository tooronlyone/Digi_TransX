-- Rules 1–2. Additive snapshots: historical bids, orders and invoices are not
-- repriced. Apply before the matching application release in a transaction.
ALTER TABLE public.shipment_bids
 ADD COLUMN IF NOT EXISTS market_key text,
 ADD COLUMN IF NOT EXISTS market_reference_average numeric,
 ADD COLUMN IF NOT EXISTS market_minimum_bid numeric(18,2),
 ADD COLUMN IF NOT EXISTS market_maximum_bid numeric(18,2),
 ADD COLUMN IF NOT EXISTS market_rating_snapshot numeric,
 ADD COLUMN IF NOT EXISTS market_sample_count integer,
 ADD COLUMN IF NOT EXISTS market_bootstrap boolean,
 ADD COLUMN IF NOT EXISTS market_ineligible_reason text;

DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM public.shipment_bids WHERE status IN('pending','accepted')
           GROUP BY order_id,transporter_user_id HAVING count(*)>1) THEN
   RAISE EXCEPTION 'Duplicate active bids require explicit reconciliation before Rules 1–4 migration';
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS shipment_bids_one_active_transporter
 ON public.shipment_bids(order_id,transporter_user_id) WHERE status IN('pending','accepted');
CREATE INDEX IF NOT EXISTS shipment_bids_market_eligible
 ON public.shipment_bids(market_key,created_at,id) WHERE status='pending' AND market_ineligible_reason IS NULL;
CREATE INDEX IF NOT EXISTS shipments_comparable_route_weight
 ON public.shipments(lower(regexp_replace(btrim(pickup_city),'[[:space:]]+',' ','g')),
                     lower(regexp_replace(btrim(dropoff_city),'[[:space:]]+',' ','g')),goods_weight_tons);

CREATE OR REPLACE FUNCTION public.preserve_bid_market_audit() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$ BEGIN
 IF (NEW.market_key,NEW.market_reference_average,NEW.market_minimum_bid,NEW.market_maximum_bid,
     NEW.market_rating_snapshot,NEW.market_sample_count,NEW.market_bootstrap,NEW.bid_price,
     NEW.order_id,NEW.transporter_user_id,NEW.truck_id)
 IS DISTINCT FROM
    (OLD.market_key,OLD.market_reference_average,OLD.market_minimum_bid,OLD.market_maximum_bid,
     OLD.market_rating_snapshot,OLD.market_sample_count,OLD.market_bootstrap,OLD.bid_price,
     OLD.order_id,OLD.transporter_user_id,OLD.truck_id) THEN
   RAISE EXCEPTION 'Bid identity, price and submission reference are immutable';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.preserve_bid_market_audit() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS preserve_bid_market_audit ON public.shipment_bids;
CREATE TRIGGER preserve_bid_market_audit BEFORE UPDATE ON public.shipment_bids
 FOR EACH ROW EXECUTE FUNCTION public.preserve_bid_market_audit();

ALTER TABLE public.marketplace_orders ADD COLUMN IF NOT EXISTS business_fee_version text;
CREATE OR REPLACE FUNCTION public.preserve_marketplace_fee_snapshot() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$ BEGIN
 IF NEW.business_fee_version IS DISTINCT FROM OLD.business_fee_version OR
    (OLD.business_fee_version='rules_1_4_v1' AND
     (NEW.buyer_user_id,NEW.shop_user_id,NEW.total_parts_amount,NEW.delivery_fee,NEW.net_total,NEW.payment_method)
     IS DISTINCT FROM
     (OLD.buyer_user_id,OLD.shop_user_id,OLD.total_parts_amount,OLD.delivery_fee,OLD.net_total,OLD.payment_method)) THEN
   RAISE EXCEPTION 'Accepted marketplace funding and fee snapshots are immutable; post an authorized reversal';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.preserve_marketplace_fee_snapshot() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS marketplace_fee_snapshot_immutable ON public.marketplace_orders;
CREATE TRIGGER marketplace_fee_snapshot_immutable BEFORE UPDATE ON public.marketplace_orders
 FOR EACH ROW EXECUTE FUNCTION public.preserve_marketplace_fee_snapshot();
CREATE TABLE IF NOT EXISTS public.marketplace_financial_events(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES public.marketplace_orders(id),
 event_type text NOT NULL CHECK(event_type IN('settlement','refund','escrow_return')),
 idempotency_key text NOT NULL UNIQUE,
 request_fingerprint text,
 gross_amount numeric(18,2) NOT NULL CHECK(gross_amount>=0 AND gross_amount<'Infinity'::numeric),
 eligible_sale_amount numeric(18,2) NOT NULL CHECK(eligible_sale_amount>=0 AND eligible_sale_amount<'Infinity'::numeric),
 platform_fee numeric(18,2) NOT NULL CHECK(platform_fee>=0 AND platform_fee<'Infinity'::numeric),
 seller_amount numeric(18,2) NOT NULL CHECK(seller_amount>=0 AND seller_amount<'Infinity'::numeric),
 fee_breakdown jsonb NOT NULL,
 actor_user_id bigint REFERENCES public.users(id),
 decision_reference text,
 reason text,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(gross_amount=platform_fee+seller_amount),
 CHECK(eligible_sale_amount<=gross_amount),
 CHECK(event_type='settlement' OR
       (actor_user_id IS NOT NULL AND length(btrim(reason))>0 AND length(btrim(decision_reference))>0))
);
CREATE UNIQUE INDEX IF NOT EXISTS marketplace_financial_one_settlement
 ON public.marketplace_financial_events(order_id) WHERE event_type='settlement';
ALTER TABLE public.marketplace_financial_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.marketplace_financial_events FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT ON public.marketplace_financial_events TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.marketplace_financial_events_id_seq TO service_role;
DROP POLICY IF EXISTS marketplace_financial_backend ON public.marketplace_financial_events;
CREATE POLICY marketplace_financial_backend ON public.marketplace_financial_events
 FOR ALL TO service_role USING(true) WITH CHECK(true);
CREATE OR REPLACE FUNCTION public.prevent_marketplace_financial_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$ BEGIN
 RAISE EXCEPTION 'Marketplace financial events are immutable; post a reversal';
END $$;
REVOKE ALL ON FUNCTION public.prevent_marketplace_financial_mutation() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS marketplace_financial_immutable ON public.marketplace_financial_events;
CREATE TRIGGER marketplace_financial_immutable BEFORE UPDATE OR DELETE ON public.marketplace_financial_events
 FOR EACH ROW EXECUTE FUNCTION public.prevent_marketplace_financial_mutation();
