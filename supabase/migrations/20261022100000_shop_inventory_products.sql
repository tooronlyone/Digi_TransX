BEGIN;

CREATE TABLE IF NOT EXISTS public.shop_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    category TEXT NOT NULL DEFAULT '',
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    stock_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    unit TEXT NOT NULL DEFAULT 'piece' CHECK (unit IN (
        'piece', 'pair', 'set', 'dozen', 'pack', 'box', 'bottle', 'can',
        'liter', 'milliliter', 'gallon', 'kilogram', 'gram', 'meter', 'foot'
    )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_shop_products_owner_name
    ON public.shop_products(shop_user_id, name);

ALTER TABLE public.shop_products ENABLE ROW LEVEL SECURITY;

COMMIT;
