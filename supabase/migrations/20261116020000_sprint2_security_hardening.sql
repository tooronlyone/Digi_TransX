-- Sprint 2 Security Remediation (V1-SEC-006 & V1-SEC-010)
-- 1. Action-bound single-use administrator reauthentication step-up proofs
-- 2. Pending withdrawal indexing and idempotent withdrawal-limit upgrades

BEGIN;

CREATE INDEX IF NOT EXISTS idx_wallet_withdrawal_requests_pending
    ON public.wallet_withdrawal_requests (user_id, status)
    WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS public.admin_step_up_authorizations (
    authorization_id    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             bigint NOT NULL REFERENCES public.users (id),
    session_id          uuid NOT NULL,
    trusted_device_id   bigint NOT NULL,
    credentials_version integer NOT NULL CHECK (credentials_version >= 0),
    proof_digest        bytea NOT NULL,
    action_key          text NOT NULL,
    resource_type       text NOT NULL,
    resource_id         bigint NOT NULL,
    request_fingerprint bytea NOT NULL,
    state               text NOT NULL DEFAULT 'available',
    issued_at           timestamptz NOT NULL DEFAULT now(),
    consumed_at         timestamptz,
    expired_at          timestamptz,
    invalidated_at      timestamptz,
    expires_at          timestamptz NOT NULL DEFAULT (now() + interval '3 minutes'),
    CONSTRAINT admin_step_up_session_binding_fk
        FOREIGN KEY (session_id, user_id, trusted_device_id)
        REFERENCES public.user_sessions (session_id, user_id, trusted_device_id),
    CONSTRAINT admin_step_up_device_binding_fk
        FOREIGN KEY (trusted_device_id, user_id)
        REFERENCES public.trusted_devices (id, user_id),
    CONSTRAINT admin_step_up_proof_unique UNIQUE (proof_digest),
    CONSTRAINT admin_step_up_proof_shape CHECK (octet_length(proof_digest) = 32),
    CONSTRAINT admin_step_up_request_shape CHECK (octet_length(request_fingerprint) = 32),
    CONSTRAINT admin_step_up_descriptor_shape CHECK (
        resource_id > 0
        AND action_key ~ '^[a-z][a-z0-9_.]{1,95}$'
        AND resource_type ~ '^[a-z][a-z0-9_]{0,47}$'
    ),
    CONSTRAINT admin_step_up_exact_lifetime CHECK (
        expires_at = issued_at + interval '3 minutes'
    ),
    CONSTRAINT admin_step_up_state_shape CHECK (
        (state = 'available' AND consumed_at IS NULL AND expired_at IS NULL AND invalidated_at IS NULL)
        OR (state = 'consumed' AND consumed_at IS NOT NULL AND expired_at IS NULL AND invalidated_at IS NULL)
        OR (state = 'expired' AND expired_at IS NOT NULL AND consumed_at IS NULL AND invalidated_at IS NULL)
        OR (state = 'invalidated' AND invalidated_at IS NOT NULL AND consumed_at IS NULL AND expired_at IS NULL)
    ),
    CONSTRAINT admin_step_up_timestamp_order CHECK (
        expires_at > issued_at
        AND (consumed_at IS NULL OR consumed_at >= issued_at)
        AND (expired_at IS NULL OR expired_at >= issued_at)
        AND (invalidated_at IS NULL OR invalidated_at >= issued_at)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS admin_step_up_one_available_descriptor
    ON public.admin_step_up_authorizations
       (user_id, session_id, action_key, resource_type, resource_id, request_fingerprint)
    WHERE state = 'available';

CREATE INDEX IF NOT EXISTS admin_step_up_expiry_state_idx
    ON public.admin_step_up_authorizations (state, expires_at);

CREATE INDEX IF NOT EXISTS admin_step_up_user_session_idx
    ON public.admin_step_up_authorizations (user_id, session_id, issued_at DESC);

ALTER TABLE public.admin_step_up_authorizations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_step_up_authorizations FROM PUBLIC, anon, authenticated;
DROP POLICY IF EXISTS backend_only ON public.admin_step_up_authorizations;
CREATE POLICY backend_only ON public.admin_step_up_authorizations
    FOR ALL TO service_role USING (true) WITH CHECK (true);

COMMENT ON TABLE public.admin_step_up_authorizations IS
    'Server-verified, short-lived single-use administrator step-up authorization proofs bound to action and target.';

CREATE TABLE IF NOT EXISTS public.withdrawal_limit_upgrade_requests (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
    wallet_id       bigint NOT NULL,
    tier            integer NOT NULL CHECK (tier BETWEEN 1 AND 4),
    duration_years  integer NOT NULL CHECK (duration_years IN (3, 5)),
    fee_amount      numeric(14,2) NOT NULL CHECK (fee_amount > 0),
    expires_at      text NOT NULL,
    idempotency_key text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT wlu_wallet_owner_fk
        FOREIGN KEY (wallet_id, user_id) REFERENCES public.wallets (id, user_id) ON DELETE RESTRICT,
    CONSTRAINT wlu_idempotency_shape CHECK (
        length(btrim(idempotency_key)) BETWEEN 1 AND 200
        AND idempotency_key = btrim(idempotency_key)
    ),
    CONSTRAINT uniq_wlu_user_idempotency UNIQUE (user_id, idempotency_key)
);

ALTER TABLE public.withdrawal_limit_upgrade_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.withdrawal_limit_upgrade_requests FROM PUBLIC, anon, authenticated;
DROP POLICY IF EXISTS backend_only ON public.withdrawal_limit_upgrade_requests;
CREATE POLICY backend_only ON public.withdrawal_limit_upgrade_requests
    FOR ALL TO service_role USING (true) WITH CHECK (true);

COMMENT ON TABLE public.withdrawal_limit_upgrade_requests IS
    'Idempotent ledger records for transporter withdrawal limit upgrades.';

COMMIT;
