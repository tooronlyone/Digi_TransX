create or replace function public.protect_approved_reserve_reference() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
declare v_count integer; v_ceiling numeric;
begin
 if TG_OP in ('UPDATE','DELETE') and (OLD.truck_count in (15,40,70,100,200) or OLD.approved_at is not null) then
  raise exception 'Approved fleet reserve reference points and approved configurations are immutable';
 end if;
 if TG_OP='DELETE' then return OLD; end if;
 v_count:=NEW.truck_count;
 v_ceiling:=case v_count when 15 then 200000 when 40 then 300000 when 70 then 500000 when 100 then 700000 when 200 then 1000000 else null end;
 if v_ceiling is not null and NEW.ceiling<>v_ceiling then
  raise exception 'Reserve reference ceiling conflicts with the approved specification';
 end if;
 if NEW.approved_at is not null and (NEW.approved_by is null or length(btrim(coalesce(NEW.approval_evidence,'')))<10) then
  raise exception 'Custom fleet reserve configuration requires documented business approval';
 end if;
 if NEW.approved_at is not null and not exists(select 1 from public.users u where u.id=NEW.approved_by and u.role='admin') then
  raise exception 'Custom fleet reserve approval requires an authorized administrator';
 end if;
 return NEW;
end $$;
revoke all on function public.protect_approved_reserve_reference() from public,anon,authenticated;
drop trigger if exists approved_reserve_reference_immutable on public.security_reserve_brackets;
create trigger approved_reserve_reference_immutable before insert or update or delete on public.security_reserve_brackets for each row execute function public.protect_approved_reserve_reference();

