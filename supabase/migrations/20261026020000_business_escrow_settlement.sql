create or replace function public.protect_versioned_booking_terms() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if OLD.business_rules_version is not null then
  if TG_OP='DELETE' then raise exception 'Versioned booking financial history is immutable'; end if;
  if (NEW.business_rules_version,NEW.financial_terms_snapshot,NEW.fee_breakdown,
      NEW.bid_price,NEW.company_fee,NEW.transporter_amount,NEW.company_share_percent,
      NEW.transporter_share_percent,NEW.wallet_funded_amount,NEW.card_funded_amount,
      NEW.funding_source,NEW.insurance_notice_accepted_at,NEW.insurance_notice_version,
      NEW.trip_id,NEW.shipment_id,NEW.invoice_number,NEW.client_user_id,NEW.transporter_user_id,
      NEW.processing_fee_percent,NEW.processing_fee_amount,NEW.total_card_charge)
    is distinct from
     (OLD.business_rules_version,OLD.financial_terms_snapshot,OLD.fee_breakdown,
      OLD.bid_price,OLD.company_fee,OLD.transporter_amount,OLD.company_share_percent,
      OLD.transporter_share_percent,OLD.wallet_funded_amount,OLD.card_funded_amount,
      OLD.funding_source,OLD.insurance_notice_accepted_at,OLD.insurance_notice_version,
      OLD.trip_id,OLD.shipment_id,OLD.invoice_number,OLD.client_user_id,OLD.transporter_user_id,
      OLD.processing_fee_percent,OLD.processing_fee_amount,OLD.total_card_charge) then
    raise exception 'Versioned booking financial terms are immutable';
  end if;
 end if;
 if TG_OP='DELETE' then return OLD; end if;
 return NEW;
end $$;
revoke all on function public.protect_versioned_booking_terms() from public,anon,authenticated;
drop trigger if exists versioned_booking_terms_immutable on public.payments;
create trigger versioned_booking_terms_immutable before update or delete on public.payments for each row execute function public.protect_versioned_booking_terms();

