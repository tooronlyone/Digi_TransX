create or replace function public.protect_business_financial_history() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if TG_OP='DELETE' then raise exception 'Financial history is immutable'; end if;
 if TG_TABLE_NAME='freight_settlements' and
    (to_jsonb(NEW)-array['status','second_released_at']) is distinct from
    (to_jsonb(OLD)-array['status','second_released_at']) then
    raise exception 'Settlement amounts and timestamps are immutable';
 elsif TG_TABLE_NAME<>'freight_settlements' then
    raise exception 'Financial/evidence records are append-only';
 end if;
 return NEW;
end $$;
