-- No treasury, liquidity, credit, reserve forfeiture or driver credential is
-- invented by migration. An independently reconciled treasury is mandatory.
-- Add one bounded action to the existing one-use MPIN authorization model.
ALTER TABLE public.mpin_step_up_authorizations DROP CONSTRAINT IF EXISTS mpin_step_up_descriptor_shape;
ALTER TABLE public.mpin_step_up_authorizations ADD CONSTRAINT mpin_step_up_descriptor_shape CHECK(
    credential_generation>0 AND resource_id>0
    AND action_key ~ '^[a-z][a-z0-9_.]{1,95}$'
    AND resource_type ~ '^[a-z][a-z0-9_]{0,47}$'
    AND (amount_minor IS NULL OR amount_minor>0)
    AND ((amount_minor IS NULL AND currency IS NULL)
      OR (amount_minor IS NOT NULL AND currency ~ '^[A-Z]{3}$'))
    AND (funding_source IS NULL OR funding_source='wallet'
      OR (action_key='fuel.voucher.authorize' AND resource_type='trip'
          AND funding_source='wallet_and_credit' AND amount_minor IS NOT NULL AND destination_digest IS NOT NULL))
);
