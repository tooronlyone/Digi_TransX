    CHECK(actual_liters IS NULL OR (actual_liters>0 AND (max_liters IS NULL OR actual_liters<=max_liters))),
    CHECK(status<>'dispensed' OR (actual_amount=wallet_utilized+credit_utilized AND dispense_id IS NOT NULL AND finalized_at IS NOT NULL)),
    CHECK(status NOT IN('verified','dispensed') OR (redeemed_station_id IS NOT NULL AND redemption_digest IS NOT NULL))
);
