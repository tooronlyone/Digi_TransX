BEGIN;

CREATE TABLE IF NOT EXISTS public.shop_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    receipt_number TEXT NOT NULL UNIQUE,
    purchaser_name TEXT NOT NULL DEFAULT '',
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    amount_paid NUMERIC(14,2) NOT NULL CHECK (amount_paid >= total_amount),
    change_amount NUMERIC(14,2) NOT NULL CHECK (change_amount >= 0),
    sale_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_shop_sales_owner_date
    ON public.shop_sales(shop_user_id, sale_date DESC);

CREATE TABLE IF NOT EXISTS public.shop_sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES public.shop_sales(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.shop_products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    unit TEXT NOT NULL DEFAULT 'piece',
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX IF NOT EXISTS idx_shop_sale_items_sale ON public.shop_sale_items(sale_id);

ALTER TABLE public.shop_sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shop_sale_items ENABLE ROW LEVEL SECURITY;

COMMIT;
